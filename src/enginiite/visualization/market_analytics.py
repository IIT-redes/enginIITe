    hourly_path = os.path.join(out_dir, 'VoltagePenaltyMarketHealthHourly_' + market_tag + '.csv')
    hourly.to_csv(hourly_path, index=False)

    def _stats_or_nan(values):
        arr = np.asarray(values, dtype=float)
        arr = arr[np.isfinite(arr)]
        if arr.size == 0:
            return dict(count=0, mean=np.nan, median=np.nan, p95=np.nan, max=np.nan)
        return dict(count=int(arr.size), mean=float(np.mean(arr)), median=float(np.median(arr)), p95=float(np.percentile(arr, 95)), max=float(np.max(arr)))

    amp_vals = _flatten_finite_values(amplification)
