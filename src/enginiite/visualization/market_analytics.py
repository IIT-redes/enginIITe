    alpha_hour = _hour_sum(alpha, hours)
    alpha_primo_hour = _hour_sum(alpha_primo, hours)
    beta_hour = _hour_sum(beta, hours)
    voltage_to_cm_ratio = alpha_primo_hour / (beta_hour + eps)

