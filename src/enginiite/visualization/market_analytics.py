def _parse_hour_from_filename(filename):
    """
    Parse hour token from filenames like:
        ..._h00_...
        ..._h17_...
        ..._h8707_...
    """
    m = re.search(r"_h(\d+)", filename)
    if m:
        return str(int(m.group(1)))
    return None


def _classify_sensitivity_file(filename):
    """
    Classify matrix file from its name.

    Expected examples
    -----------------
    HVMP_FSPA_h00_...
    HVMQ_FSPR_h00_...
    HCM_... maybe FSPA / FSPR
    or similar naming using HVM / HCM and FSPA / FSPR.

    Output
    ------
    one of:
        VC_P
        VC_Q
        CM_P
        CM_Q
        None
    """
    name = os.path.basename(filename).upper()

    is_vc = "HVM" in name
    is_cm = "HCM" in name

    # Active if it contains FSPA
    # Reactive if it contains FSPR
    is_p = "FSPA" in name
    is_q = "FSPR" in name

    if is_vc and is_p:
        return "VC_P"
    if is_vc and is_q:
        return "VC_Q"
    if is_cm and is_p:
        return "CM_P"
    if is_cm and is_q:
        return "CM_Q"
    return None


def _scan_sensitivity_files(folder):
    """
    Scan a folder recursively and classify all sensitivity CSV files.
    """
    results = {"VC_P": [], "VC_Q": [], "CM_P": [], "CM_Q": []}

    if folder is None or (not os.path.exists(folder)):
        return results

    for root, _, files in os.walk(folder):
        for f in files:
            if not f.lower().endswith(".csv"):
                continue

            full = os.path.join(root, f)
            cls = _classify_sensitivity_file(f)
            hr = _parse_hour_from_filename(f)

            if cls is not None and hr is not None:
                results[cls].append((hr, full))

    for k in results:
        results[k] = sorted(results[k], key=lambda x: int(x[0]))

    return results


def _load_matrix_metrics(file_list):
    """
    For a classified list of sensitivity matrices, compute hour-by-hour metrics.

    Metrics
    -------
    mean_abs : mean absolute coefficient
    max_abs  : maximum absolute coefficient
    drift    : relative Frobenius-norm difference from first hour

    These metrics help show operating-point dependence.
    """
    rows = []

    matrices = []

    for hr, path in file_list:
        try:
            df = pd.read_csv(path, index_col=0)
            df = _safe_numeric_df(df)
            arr = df.values.astype(float)
            matrices.append((hr, arr))

            rows.append({
                "hour": hr,
                "mean_abs": float(np.mean(np.abs(arr))),
                "max_abs": float(np.max(np.abs(arr))),
                "rows": int(arr.shape[0]),
                "cols": int(arr.shape[1]),
            })
        except Exception as e:
            print("WARNING: could not read sensitivity matrix:", path, "|", e)

    out = pd.DataFrame(rows)

    if out.empty:
        return out

    # Compute drift relative to first-hour matrix.
    drift_list = []
    ref_hour, ref_matrix = matrices[0]
    ref_norm = np.linalg.norm(ref_matrix)
    denom = max(ref_norm, 1e-12)

    for hr, arr in matrices:
        if arr.shape != ref_matrix.shape:
            drift = np.nan
        else:
            drift = np.linalg.norm(arr - ref_matrix) / denom
        drift_list.append({"hour": hr, "drift_from_first_hour": drift})

    drift_df = pd.DataFrame(drift_list)

    out = out.merge(drift_df, on="hour", how="left")
    out = out.sort_values(by="hour", key=lambda s: s.astype(int))
    return out


