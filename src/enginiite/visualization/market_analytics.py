def _matrix_to_long(matrix, metric, unit=None, group=None):
    """Convert an asset/bus x hour matrix into a cell-level long table.

    The returned table preserves the cell identity. This is essential for
    residual interval diagnostics: the box/interval plot explains the
    distribution, while hover labels and the companion ranked-cell figure show
    exactly which asset/bus and hour produce each point.
    """
    cols = ["metric", "asset_or_bus", "hour", "value", "unit", "group", "abs_value", "signed_direction"]
    if matrix is None or matrix.empty:
        return pd.DataFrame(columns=cols)
    tmp = matrix.copy()
    tmp.index = [str(i) for i in tmp.index]
    tmp.columns = [str(c) for c in tmp.columns]
    long = tmp.reset_index().melt(id_vars=tmp.index.name or "index", var_name="hour", value_name="value")
    first = long.columns[0]
    long = long.rename(columns={first: "asset_or_bus"})
    long.insert(0, "metric", metric)
    long["value"] = pd.to_numeric(long["value"], errors="coerce")
    long = long.replace([np.inf, -np.inf], np.nan).dropna(subset=["value"])
    long["unit"] = unit or ""
    long["group"] = group or ""
    long["abs_value"] = long["value"].abs()
    long["signed_direction"] = np.where(long["value"] > 0, "positive", np.where(long["value"] < 0, "negative", "zero"))
    return long[cols]


def _top_cells_from_matrix(matrix, metric, unit, group, n=12, tol=1e-12):
    """Return top absolute-valued cells with asset/bus and hour identity."""
    long = _matrix_to_long(matrix, metric, unit=unit, group=group)
    if long.empty:
        return long
    nonzero = long[long["abs_value"] > tol].copy()
    if nonzero.empty:
        nonzero = long.copy()
    nonzero = nonzero.sort_values("abs_value", ascending=False).head(int(n)).copy()
    nonzero["cell_label"] = nonzero["asset_or_bus"].astype(str) + " @ h" + nonzero["hour"].astype(str)
    return nonzero


