def _load_to_grid_view(df):
    """
    Convert load flexibility to grid-support viewpoint.

    Interpretation:
    - In load convention, increasing load consumption is bad for the grid
      from active-power support viewpoint, so it is treated as DOWNWARD.
    - Decreasing load consumption helps the grid, so it is treated as UPWARD.

    Therefore:
        grid_view = - raw_load_deviation
    """
    if df is None:
        return None
    return -df


def _generator_to_grid_view(df):
    """
    Generator flexibility is already naturally aligned:
    - Increase generation = UPWARD
    - Decrease generation = DOWNWARD
    """
    return df


def _get_storage_net_active(market_sheets):
    """
    Storage signed active flexibility in grid-support convention.

    Internal optimisation convention for storage:
        W_C_internal = Winj_internal + Wads_internal
        Winj_internal >= 0  (discharge / injection)
        Wads_internal <= 0  (charge / absorption)
        DW_C_internal = W_C_internal - Winit_internal

    Export convention in model_results_*.xlsx:
        ess_conv = ['DR_', 'R_', 'DW_', 'W_', 'Winj_', 'Wads_', 'RATIO_']
    so exported DW_C, W_C, Winj_C and Wads_C are sign-flipped relative to
    the internal injection convention and align with the pandapower storage
    profile convention: positive active power is charging/absorption.

    For flexibility-activation figures we need grid-support convention:
        positive = upward support = increased net injection / reduced absorption
        negative = downward support = increased absorption / reduced injection

    Therefore the activation is:
        P_storage_grid_support = -DW_C_exported

    If DW_C is unavailable, use final operating components. In exported sheets,
    injection magnitude is -Winj_C_exported and absorption magnitude is
    Wads_C_exported, so net injection is:
        P_storage_grid_support = (-Winj_C_exported) - Wads_C_exported
    This fallback is a final operating point, and equals activation only when
    the initial storage active power is zero.
    """
    dw_c = market_sheets.get("DW_C")
    if dw_c is not None:
        return -dw_c

    winj = market_sheets.get("Winj_C")
    wads = market_sheets.get("Wads_C")

    if winj is not None and wads is not None:
        common_idx = [i for i in winj.index if i in wads.index]
        common_cols = [c for c in winj.columns if c in wads.columns]
        if len(common_idx) > 0 and len(common_cols) > 0:
            return -winj.loc[common_idx, common_cols] - wads.loc[common_idx, common_cols]

    return None


def _get_storage_net_reactive(market_sheets):
    """Storage signed reactive flexibility in grid-support convention.

    DR_C is also included in ess_conv, so exported DR_C is sign-flipped
    relative to the internal injection convention used by the sensitivity
    matrices. For upward/downward reactive provision plots, convert it back:
        Q_storage_grid_support = -DR_C_exported
    """
    dr_c = market_sheets.get("DR_C")
    if dr_c is not None:
        return -dr_c
    return None


def _split_up_down(df):
    """
    Split signed signal into upward and downward components.

    Returns
    -------
    upward_df : positive part
    downward_df : absolute value of negative part
    """
    if df is None:
        return None, None

    up = df.clip(lower=0.0)
    down = -df.clip(upper=0.0)
    return up, down


