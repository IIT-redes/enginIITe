def _standardize_slack_like(df, target_index, target_columns, positive_only=False, abs_values=False):
    """Standardize a market slack sheet to target asset/bus x hour shape.

    The market-result sheets can appear as entity x hour or hour x entity.
    This helper aligns them by hour labels and then by exact/weak labels. If no
    labels match but dimensions are compatible, it falls back to positional
    mapping. This keeps diagnostics robust across platform revisions.
    """
    if df is None or df.empty:
        return pd.DataFrame(index=list(target_index), columns=list(target_columns), dtype=float).fillna(0.0)
    out = df.copy()
    out = out.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(0.0)
    out.index = [str(i) for i in out.index]
    out.columns = [str(c) for c in out.columns]
    target_index = [str(i) for i in target_index]
    target_columns = [str(c) for c in target_columns]

    # Orient so columns are hours.
    common_cols = [c for c in target_columns if c in out.columns]
    common_idx_as_cols = [c for c in target_columns if c in out.index]
    if len(common_idx_as_cols) > len(common_cols):
        out = out.T
        out.index = [str(i) for i in out.index]
        out.columns = [str(c) for c in out.columns]

    # Align columns/hours.
    aligned = pd.DataFrame(0.0, index=target_index, columns=target_columns)
    common_hours = [c for c in target_columns if c in out.columns]
    if not common_hours:
        # Positional fallback for hours.
        n = min(len(target_columns), out.shape[1])
        tmp = out.iloc[:, :n].copy()
        tmp.columns = target_columns[:n]
    else:
        tmp = out[common_hours].copy()

    # Align rows/entities.
    source_rows = list(tmp.index)
    direct = {str(r): str(r) for r in source_rows if str(r) in target_index}
    weak_source = {_normalize_label_for_alignment(r): str(r) for r in source_rows}
    for ti in target_index:
        src = direct.get(ti)
        if src is None:
            src = weak_source.get(_normalize_label_for_alignment(ti))
        if src is not None and src in tmp.index:
            aligned.loc[ti, [c for c in tmp.columns if c in aligned.columns]] = tmp.loc[src, [c for c in tmp.columns if c in aligned.columns]].to_numpy(dtype=float)

    if (aligned.abs().sum().sum() == 0.0) and len(source_rows) and len(target_index):
        # Positional fallback only when label alignment gave nothing.
        nr = min(len(target_index), tmp.shape[0])
        nc = min(len(target_columns), tmp.shape[1])
        aligned.iloc[:nr, :nc] = tmp.iloc[:nr, :nc].to_numpy(dtype=float)

    if positive_only:
        aligned = aligned.clip(lower=0.0)
    if abs_values:
        aligned = aligned.abs()
    return aligned.fillna(0.0)




def _linear_voltage_from_va_alpha(market_sheets, target_index, target_columns):
    """Return the raw sensitivity-based voltage estimate implied by the market model.

    In the optimization constraints, VA is a bounded decision variable.  For
    voltage accuracy studies it must not be interpreted as the physical linear
    voltage estimate.  The constraint has the form, depending on the pre-market
    voltage condition,

        VA - V_before - alpha_DVpu - sensitivity_effect {==, >=, <=} 0

    Therefore the raw sensitivity voltage that should be compared with the
    nonlinear AC post-market voltage is represented by:

        V_linear_raw = VA - alpha_DVpu

    This helper aligns both sheets to the AC bus x hour matrix.  It returns
    None if VA is not available, because alpha_DVpu alone is only the clipping
    correction/slack and not a voltage estimate.
    """
    va_src = market_sheets.get("VA") if isinstance(market_sheets, dict) else None
    if va_src is None or getattr(va_src, "empty", True):
        return None
    pilot_ids = market_sheets.get("_pilot_bus_ids", []) if isinstance(market_sheets, dict) else []
    if pilot_ids and len(pilot_ids) == getattr(va_src, "shape", [0])[0]:
        va_src = va_src.copy()
        va_src.index = [str(x) for x in pilot_ids]
    va = _standardize_slack_like(va_src, target_index, target_columns, abs_values=False)
    alpha_src = market_sheets.get("alpha_DVpu") if isinstance(market_sheets, dict) else None
    if alpha_src is None or getattr(alpha_src, "empty", True):
        alpha_src = market_sheets.get("ABS_alpha_DVpu") if isinstance(market_sheets, dict) else None
    if alpha_src is None or getattr(alpha_src, "empty", True):
        alpha_src = market_sheets.get("ABS_alphaDVpu") if isinstance(market_sheets, dict) else None
    if pilot_ids and alpha_src is not None and len(pilot_ids) == getattr(alpha_src, "shape", [0])[0]:
        alpha_src = alpha_src.copy()
        alpha_src.index = [str(x) for x in pilot_ids]
    alpha = _standardize_slack_like(alpha_src, target_index, target_columns, abs_values=False)
    vlin = (va - alpha).replace([np.inf, -np.inf], np.nan)
    target_rows = [str(i) for i in target_index]
    target_cols = [str(c) for c in target_columns]
    vlin = vlin.reindex(index=target_rows, columns=target_cols)
    if pilot_ids:
        pilot_set = {str(x) for x in pilot_ids}
        for r in target_rows:
            if r not in pilot_set:
                vlin.loc[r, :] = np.nan
    return vlin


def _voltage_accuracy_error_matrix(post_vm, market_sheets):
    """Signed AC-minus-linear voltage error matrix in pu.

    Positive values mean the exact AC post-market voltage is higher than the
    raw sensitivity model estimate.  The matrix is bus x hour, aligned to the
    post-market AC vm_pu.csv table.
    """
    if post_vm is None or getattr(post_vm, "empty", True):
        return pd.DataFrame(), pd.DataFrame()
    vlin = _linear_voltage_from_va_alpha(market_sheets, post_vm.index, post_vm.columns)
    if vlin is None or getattr(vlin, "empty", True):
        return pd.DataFrame(), pd.DataFrame()
    ac = post_vm.apply(pd.to_numeric, errors="coerce")
    err = ac - vlin
    return vlin, err


