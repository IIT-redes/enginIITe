_MARKET_TAG_PATTERN = re.compile(
    r"([A-Za-z0-9]+(?:_[A-Za-z0-9]+)+_(?:PQ|P|Q)_VL\d+_F\d+_SK\d+(?:_[A-Za-z0-9]+(?:_[A-Za-z0-9]+)*)?)"
)


def _extract_market_tag_from_text(text):
    """
    Extract a full enginIITe market/scenario tag from a string.

    Expected example:
        net_CMVC_PQ_VL01_F05_SK01_T1
    """
    if text is None:
        return None

    # Prefer an exact path segment over
    # a greedy match inside a prefixed output filename.
    normalized_parts = re.split(r"[\\/]", os.path.normpath(str(text)))
    exact_pattern = re.compile(
        r"^[A-Za-z0-9]+(?:_[A-Za-z0-9]+)+_(?:PQ|P|Q)_VL\d+_F\d+_SK\d+(?:_[A-Za-z0-9]+(?:_[A-Za-z0-9]+)*)?$"
    )
    for part in reversed(normalized_parts):
        if exact_pattern.fullmatch(part):
            return part

    match = _MARKET_TAG_PATTERN.search(str(text))
    if match:
        return match.group(1)

    return None


def _scenario_outer_folder_from_market_tag(market_tag):
    """
    Build the smart scenario-group folder name used by the platform.

    Example
    -------
    Full market tag:
        net_CMVC_PQ_VL01_F05_SK01_T1

    Scenario-group folder:
        net_CMVC_SK01_T1
    """
    if market_tag is None:
        return None

    match = re.match(
        r"^(.+)_([^_]+)_(PQ|P|Q)_(VL\d+)_(F\d+)_(SK\d+)(?:_(.+))?$",
        str(market_tag),
    )
    if match:
        network, market_model, _, _, _, storage_case, suffix = match.groups()
        return "_".join(filter(None, (network, market_model, storage_case, suffix)))

    return None


def _find_data_out_root(path_text):
    """
    Return the path up to and including data_out if it exists in path_text.
    """
    if path_text is None:
        return None

    normalized = os.path.normpath(str(path_text))
    parts = normalized.split(os.sep)

    for i, part in enumerate(parts):
        if part.lower() == "data_out":
            return os.sep.join(parts[:i + 1])

    return None


def _resolve_scenario_visualization_folder(output_folder, market_tag=None, allowed_subfolder=None):
    """
    Resolve the only allowed visualization root/subfolder for this scenario.

    Final saving rule
    -----------------
    Never save into generic paths such as:
        data_out/net/T1/visualization

    Always save into:
        data_out/<network>_<market>_<storage>_<tag>/
            <full_market_tag>/
                visualization/
                    <allowed_subfolder>/

    The function also preserves valid subfolder tails. For example, if a caller
    passes:
        .../net/T1/visualization/sensitivity_resource_boxplots/HVMP_V-P

    and the filename contains the full market tag, it is redirected to:
        .../net_CMVC_SK01_T1/
            net_CMVC_PQ_VL01_F05_SK01_T1/
                visualization/sensitivity_resource_boxplots/HVMP_V-P

    Parameters
    ----------
    output_folder : str
        Folder requested by the caller.

    market_tag : str
        Full scenario tag, e.g. net_CMVC_PQ_VL01_F05_SK01_T1.

    allowed_subfolder : str or None
        Optional enforced first subfolder under visualization. Use this when a
        module must never save loose files directly in visualization.
    """
    if output_folder is None:
        output_folder = os.getcwd()

    output_folder = os.path.normpath(str(output_folder))

    if market_tag is None:
        market_tag = _extract_market_tag_from_text(output_folder)

    # Without market_tag we cannot build the smart scenario folder. Keep the
    # folder, but if an allowed_subfolder is required, still enforce it locally.
    if market_tag is None:
        if allowed_subfolder is not None:
            parts = output_folder.split(os.sep)
            if allowed_subfolder in parts:
                return output_folder
            return os.path.join(output_folder, allowed_subfolder)
        return output_folder

    outer_folder = _scenario_outer_folder_from_market_tag(market_tag)
    if outer_folder is None:
        return output_folder

    parts = output_folder.split(os.sep)

    # Preserve any valid tail after "visualization".
    tail_after_visualization = []
    lower_parts = [p.lower() for p in parts]
    if "visualization" in lower_parts:
        viz_idx = lower_parts.index("visualization")
        tail_after_visualization = parts[viz_idx + 1:]

    # Preserve an already canonical
    # market-tag folder before attempting any legacy data_out reconstruction.
    if market_tag in parts:
        idx = parts.index(market_tag)
        base_visualization = os.path.join(os.sep.join(parts[:idx + 1]), "visualization")
    else:
        data_out_root = _find_data_out_root(output_folder)
    if market_tag not in parts and data_out_root is not None:
        base_visualization = os.path.join(
            data_out_root,
            outer_folder,
            market_tag,
            "visualization",
        )
    elif market_tag not in parts and data_out_root is None:
        # Fallback without data_out: keep the given folder exactly.  Do not
        # append the tail after visualization again; otherwise a caller that
        # already passes visualization/network_technical_analytics/error_diagnostics
        # would be saved into a duplicated nested folder.
        base_visualization = output_folder
        tail_after_visualization = []

    # Enforce a required top-level subfolder if requested.
    if allowed_subfolder is not None:
        if tail_after_visualization:
            if tail_after_visualization[0] != allowed_subfolder:
                tail_after_visualization = [allowed_subfolder] + tail_after_visualization
        else:
            tail_after_visualization = [allowed_subfolder]

    if tail_after_visualization:
        return os.path.join(base_visualization, *tail_after_visualization)

    return base_visualization


def _analytics_output_subfolder_from_filename(filename):
    """
    Infer the correct network technical analytics subfolder from the figure
    name. This prevents loose files directly inside visualization/.
    """
    name = str(filename)

    if name.startswith("VoltageViolationHeatmap_") or name.startswith("CongestionHeatmap_"):
        return ["network_technical_analytics", "voltage_congestion"]

    if name.startswith("ClearedFlexibility_"):
        return ["network_technical_analytics", "flexibility_activation"]

    if name.startswith("SlackDiagnostics_"):
        return ["network_technical_analytics", "slack_diagnostics"]

    if name.startswith("StorageDashboard_"):
        return ["network_technical_analytics", "storage_operation"]

    if name.startswith("SensitivityOperatingPointDashboard_"):
        return ["network_technical_analytics", "sensitivity_operation"]

    if (name.startswith("ACMarket") or name.startswith("VoltagePenalty")):
        return ["network_technical_analytics", "error_diagnostics"]

    return ["network_technical_analytics", "other"]


def _apply_subfolder_if_needed(output_folder, subfolder_parts):
    """
    Append a required visualization subfolder only if it is not already present.
    """
    if not subfolder_parts:
        return output_folder

    parts = os.path.normpath(str(output_folder)).split(os.sep)

    if subfolder_parts[0] in parts:
        return output_folder

    return os.path.join(output_folder, *subfolder_parts)


