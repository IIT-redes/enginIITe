def _sum_positive_above(df, threshold):
    if df is None or df.empty:
        return 0.0
    arr = df.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(0.0).to_numpy(dtype=float)
    return float(np.maximum(arr - float(threshold), 0.0).sum())


def _max_positive_above(df, threshold):
    if df is None or df.empty:
        return 0.0
    arr = df.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(0.0).to_numpy(dtype=float)
    return float(np.maximum(arr - float(threshold), 0.0).max()) if arr.size else 0.0


def _count_hours_above(df, threshold):
    if df is None or df.empty:
        return 0
    num = df.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(0.0)
    return int((num.gt(float(threshold)).any(axis=0)).sum())


def _voltage_exposure(df, vmin, vmax):
    if df is None or df.empty:
        return 0.0
    num = df.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(np.nan)
    low = (float(vmin) - num).clip(lower=0.0)
    high = (num - float(vmax)).clip(lower=0.0)
    return float((low + high).fillna(0.0).to_numpy(dtype=float).sum())


def _voltage_hours(df, vmin, vmax):
    if df is None or df.empty:
        return 0
    num = df.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan)
    bad = num.lt(float(vmin)) | num.gt(float(vmax))
    return int(bad.any(axis=0).sum())


def _sheet_abs_sum(market_sheets, names):
    vals = []
    for name in names:
        df = market_sheets.get(name)
        if df is None or df.empty:
            continue
        num = df.apply(pd.to_numeric, errors="coerce").replace([np.inf, -np.inf], np.nan).fillna(0.0)
        vals.append(float(np.abs(num.to_numpy(dtype=float)).sum()))
    return float(sum(vals)) if vals else np.nan


