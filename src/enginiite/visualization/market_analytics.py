def plot_cleared_flexibility_by_type(
    market_sheets,
    output_folder,
    market_tag,
    common_output_folder=None,
    hour_labels=None,
):
    """
    Plot flexibility by resource type and direction.

    IMPORTANT INTERPRETATION
    ------------------------
    We express everything from grid-support viewpoint.

    ACTIVE POWER
    ------------
    Generator:
        increase generation -> Upward
        decrease generation -> Downward

    Storage:
        discharge/inject -> Upward
        charge/absorb   -> Downward

    Load:
        decrease consumption -> Upward
        increase consumption -> Downward

    The same directional philosophy is used for reactive activation plotting.
    """
    if hour_labels is None:
        hour_labels = []

    load_p = _load_to_grid_view(market_sheets.get("DW_A"))
    gen_p = _generator_to_grid_view(market_sheets.get("DW_B"))
    sto_p = _get_storage_net_active(market_sheets)

    load_q = _load_to_grid_view(market_sheets.get("DR_A"))
    gen_q = _generator_to_grid_view(market_sheets.get("DR_B"))
    sto_q = _get_storage_net_reactive(market_sheets)

    lpu, lpd = _split_up_down(load_p)
    gpu, gpd = _split_up_down(gen_p)
    spu, spd = _split_up_down(sto_p)

    lqu, lqd = _split_up_down(load_q)
    gqu, gqd = _split_up_down(gen_q)
    squ, sqd = _split_up_down(sto_q)

    fig = make_subplots(
        rows=2, cols=1, shared_xaxes=False, vertical_spacing=0.18,
        subplot_titles=(
            "Cleared active flexibility by resource and direction",
            "Cleared reactive flexibility by resource and direction"
        )
    )

