def _read_csv_if_exists(path):
    """Read a CSV file if it exists."""
    if os.path.exists(path):
        return pd.read_csv(path, index_col=0)
    print("WARNING: CSV not found:", path)
    return None


def _read_excel_sheet_if_exists(xls, sheet_name):
    """Read one Excel sheet if available.

    The enginIITe model-results files have mostly stable sheet names, but
    Excel exports can differ in capitalization or surrounding spaces.  This
    helper therefore tries exact matching first and then a normalized
    case-insensitive match.
    """
    if sheet_name in xls.sheet_names:
        return pd.read_excel(xls, sheet_name=sheet_name, index_col=0)
    target = str(sheet_name).strip().lower().replace(" ", "").replace("-", "_")
    for candidate in xls.sheet_names:
        key = str(candidate).strip().lower().replace(" ", "").replace("-", "_")
        if key == target:
            return pd.read_excel(xls, sheet_name=candidate, index_col=0)
    return None


def _safe_numeric_df(df):
    """Convert dataframe to numeric and replace NaN/Inf carefully."""
    if df is None:
        return None
    out = df.copy()
    out = out.apply(pd.to_numeric, errors="coerce")
    out = out.replace([np.inf, -np.inf], np.nan)
    out = out.fillna(0.0)
    return out


def _labels_to_string(labels):
    """Convert labels to strings."""
    return [str(x) for x in labels]


def _standardize_timeseries_csv(df):
    """
    enginIITe time-series CSV usually arrives as:
        rows    = hours
        columns = assets

    We convert it to:
        rows    = assets
        columns = hours
    """
    if df is None:
        return None, []

    df = _safe_numeric_df(df)
    hour_labels = _labels_to_string(df.index)

    out = df.T
    out.columns = hour_labels
    out.index = _labels_to_string(out.index)
    return out, hour_labels


def _standardize_market_sheet(df, hour_labels=None):
    """
    Standardize market result sheet to numeric asset x hour format.
    """
    if df is None:
        return None

    out = _safe_numeric_df(df)
    out.index = _labels_to_string(out.index)
    out.columns = _labels_to_string(out.columns)

    if hour_labels is not None and len(hour_labels) > 0:
        common_cols = [c for c in hour_labels if c in out.columns]
        if common_cols:
            out = out[common_cols]
    return out


def _combine_loading(line_df, trafo_df, trafo3w_df):
    """Combine line / trafo / trafo3w loading in one table."""
    frames = []

    if line_df is not None:
        x = line_df.copy()
        x.index = ["line_" + str(i) for i in x.index]
        frames.append(x)

    if trafo_df is not None:
        x = trafo_df.copy()
        x.index = ["trafo_" + str(i) for i in x.index]
        frames.append(x)

    if trafo3w_df is not None:
        x = trafo3w_df.copy()
        x.index = ["trafo3w_" + str(i) for i in x.index]
        frames.append(x)

    if len(frames) == 0:
        return None

    return pd.concat(frames, axis=0)




def _clean_slack_series(series, tolerance):
    """
    Remove numerical-noise slack from visualization.

    Values with absolute magnitude <= tolerance are set to exactly zero. If all
    values are below tolerance, the caller can still plot a flat zero curve,
    which correctly communicates that the slack is not active.
    """
    if series is None:
        return None
    out = pd.to_numeric(series, errors="coerce").fillna(0.0).copy()
    out.loc[out.abs() <= float(tolerance)] = 0.0
    return out

