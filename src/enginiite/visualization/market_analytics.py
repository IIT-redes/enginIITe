def _infer_pilot_bus_ids_from_scenario(market_result_file):
    """Infer pilot-bus IDs that map VA/alpha rows to AC bus columns.

    Preferred source is scenario_root/pilot_bus_vm_post.csv because its columns
    are the actual bus IDs and its order matches the VA/alpha row order used by
    the optimization result workbook.
    """
    try:
        scenario_root = os.path.dirname(os.path.abspath(str(market_result_file)))
        for fname in ["pilot_bus_vm_post.csv", "VPilotBus_HTS.csv", "VPilotBus24h.csv"]:
            path = os.path.join(scenario_root, fname)
            if os.path.exists(path):
                if fname == "pilot_bus_vm_post.csv":
                    df = pd.read_csv(path, index_col=0, nrows=1)
                    return [str(c) for c in df.columns]
                df = pd.read_csv(path, index_col=0)
                vals = pd.unique(df.to_numpy().ravel())
                vals = [str(int(v)) if pd.notna(v) and float(v).is_integer() else str(v) for v in vals if pd.notna(v)]
                if vals:
                    return vals
    except Exception:
        pass
    return []


