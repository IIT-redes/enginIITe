def _safe_hourly_concentration(mat):
    """Return hourly HHI and top-row share for a nonnegative matrix indexed by bus/resource."""
    if mat is None or mat.empty:
        return pd.Series(dtype=float), pd.Series(dtype=float)
    m = mat.abs().fillna(0.0)
    totals = m.sum(axis=0).replace(0.0, np.nan)
    shares = m.div(totals, axis=1)
    hhi = (shares ** 2).sum(axis=0).fillna(0.0)
    top_share = shares.max(axis=0).fillna(0.0)
    return hhi, top_share


def _save_voltage_penalty_market_health_report(market_sheets, out_dir, market_tag, market_result_file=None):
    """Inspect whether inverse self-sensitivity scaling makes voltage slack dominate the market.

    This version reads the required sheets directly from the scenario-level
    model_results_*.xlsx file whenever possible. This is important because
    alpha_DVpu/alpha_primo are bus-hour sheets, while beta is a congested
    asset-hour sheet; they must not be forced onto the same row index.
    """
    os.makedirs(out_dir, exist_ok=True)

    def _norm_name(x):
        return str(x).strip().lower().replace(' ', '').replace('-', '_')

    def _sheet_from_workbook(xlsx_path, wanted):
        if not xlsx_path or not os.path.exists(xlsx_path):
            return None
        try:
            xls = pd.ExcelFile(xlsx_path)
            wanted_key = _norm_name(wanted)
            for sh in xls.sheet_names:
                if _norm_name(sh) == wanted_key:
                    return pd.read_excel(xls, sheet_name=sh, index_col=0)
        except Exception as exc:
            print('WARNING: could not read', wanted, 'from', xlsx_path, '-', exc)
        return None

    def _get_sheet(name):
        df = None
        if isinstance(market_sheets, dict):
            df = market_sheets.get(name)
        if df is None and market_result_file is not None:
            df = _sheet_from_workbook(market_result_file, name)
        return df

    def _numeric_frame(df, abs_values=True):
        if df is None:
            return pd.DataFrame()
        try:
            out = df.copy()
            out = out.apply(pd.to_numeric, errors='coerce').replace([np.inf, -np.inf], np.nan).fillna(0.0)
            out.index = [str(i) for i in out.index]
            out.columns = [str(c) for c in out.columns]
            if abs_values:
                out = out.abs()
            return out
        except Exception:
            return pd.DataFrame()

    alpha_raw_df = _get_sheet('alpha_DVpu')
    alpha_primo_df = _get_sheet('alpha_primo')
    abs_alpha_primo_df = _get_sheet('ABS_alpha_primo')
    beta_df = _get_sheet('beta')
    abs_beta_df = _get_sheet('ABS_beta')

    alpha = _numeric_frame(alpha_raw_df, abs_values=True)
    alpha_primo = _numeric_frame(alpha_primo_df, abs_values=True)
    if alpha_primo.empty or alpha_primo.abs().sum().sum() <= 1e-12:
        alpha_primo = _numeric_frame(abs_alpha_primo_df, abs_values=True)
    beta = _numeric_frame(beta_df, abs_values=True)
    if beta.empty or beta.abs().sum().sum() <= 1e-12:
        beta = _numeric_frame(abs_beta_df, abs_values=True)

    found_flags = {
        'alpha_DVpu_found': alpha_raw_df is not None,
        'alpha_primo_found': alpha_primo_df is not None,
        'ABS_alpha_primo_found': abs_alpha_primo_df is not None,
        'beta_found': beta_df is not None,
        'ABS_beta_found': abs_beta_df is not None,
        'market_result_file_used': bool(market_result_file and os.path.exists(market_result_file)),
    }

    hours = []
