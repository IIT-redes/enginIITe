def _linear_cm_need_from_hcm(market_sheets, sens_matrix_root, scenario_root, market_tag, target_columns=None):
    """Reconstruct the physical linear CM residual from HCM matrices and cleared FSP actions.

    beta is a slack variable in the CM constraint, not the post-market linear
    loading/need.  The HCM coefficients already carry the sign of the sensitivity:
    the HCM term is evaluated after converting saved load/storage deltas to equivalent injection; negative effect means the action relieves the monitored asset.
    Therefore the raw sensitivity estimate is
        S_pre + HCMdSdP*DeltaP_inj_equiv + HCMdSdQ*DeltaQ_inj_equiv
    in MVA-need units.

    Only the studied hours written in the model action sheets are compared.
    This avoids mixing 24-hour pre-market files with 19-row post-market files.
    """
    study_hours = _infer_model_study_hour_columns(market_sheets)
    pre_need = _read_total_cm_need_matrix(scenario_root, 'total_cm_PreMKT.xlsx')
    if pre_need.empty:
        return pd.DataFrame(), pd.DataFrame()
    if study_hours:
        pre_need = pre_need.reindex(columns=study_hours).fillna(0.0)
    elif target_columns is not None:
        pre_need = pre_need.reindex(columns=[str(c) for c in target_columns]).fillna(0.0)
    sim_tag = str(market_tag).split('_')[-1] if market_tag else ''
    sens_root = _resolve_sensitivity_root_for_cm(sens_matrix_root, scenario_root)
    if not sens_root:
        return pd.DataFrame(), pd.DataFrame()
    sensitivity_delta = pd.DataFrame(0.0, index=pre_need.index, columns=pre_need.columns)
    for hpos, h in enumerate(pre_need.columns):
        for fsp_type in ['A', 'B', 'C']:
            dw = market_sheets.get('DW_' + fsp_type) if isinstance(market_sheets, dict) else None
            dr = market_sheets.get('DR_' + fsp_type) if isinstance(market_sheets, dict) else None
            mp = _read_hcm_matrix(sens_root, 'HCMdSdP', fsp_type, h, sim_tag)
            mq = _read_hcm_matrix(sens_root, 'HCMdSdQ', fsp_type, h, sim_tag)
            for mat, sheet in [(mp, dw), (mq, dr)]:
                if mat.empty or sheet is None or getattr(sheet, 'empty', True):
                    continue
                assets = [str(c) for c in mat.columns]
                n = min(mat.shape[0], sheet.shape[0])
                for i in range(n):
                    val = _sheet_value_by_hour(sheet, i, h, hpos)
                    if not np.isfinite(val) or abs(val) <= 1e-15:
                        continue
                    coeffs = mat.iloc[i, :].to_numpy(dtype=float)
                    for apos, asset in enumerate(assets):
                        if asset in sensitivity_delta.index:
                            sensitivity_delta.loc[asset, str(h)] += coeffs[apos] * val
    linear_raw_need = pre_need + sensitivity_delta
    linear_positive_need = linear_raw_need.clip(lower=0.0)
    return linear_positive_need, sensitivity_delta

