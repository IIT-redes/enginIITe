def _line_loading_color(loading):
    """Return a crisp branch color from loading percentage."""
    if pd.isna(loading):
        return "#94a3b8"
    if loading >= 100:
        return "#d62728"
    if loading >= 97:
        return "#ff7f0e"
    if loading >= 80:
        return "#2ca02c"
    return "#7a8795"


def _build_powerflow_state_traces_for_slider(
    net,
    panel_name="Pre-market",
    line_width=3.2,
    bus_size=10,
    cmap="Turbo",
    show_legend_items=False,
    show_bus_hover=False,
):
    """
    Build a constant-length trace list for one network operating point.

    The trace count is intentionally independent of result values so Plotly
    animation frames can update the pre/post topology in one single HTML file.
    """
    traces = []

    def _xy(bus_idx):
        bus_idx = int(bus_idx)
        if not hasattr(net, "bus_geodata") or net.bus_geodata.empty:
            return None
        if bus_idx not in net.bus_geodata.index:
            return None
        return (
            float(net.bus_geodata.loc[bus_idx, "x"]),
            float(net.bus_geodata.loc[bus_idx, "y"]),
        )

    # Lines.
    if hasattr(net, "line") and not net.line.empty:
        for line_idx, row in net.line.iterrows():
            if not _line_is_operational(net, line_idx, row):
                continue
            xy1 = _xy(row["from_bus"])
            xy2 = _xy(row["to_bus"])
            if xy1 is None or xy2 is None:
                continue

            loading = _safe_res(net.res_line, line_idx, "loading_percent") if hasattr(net, "res_line") else np.nan
            p_from = _safe_res(net.res_line, line_idx, "p_from_mw") if hasattr(net, "res_line") else np.nan
            q_from = _safe_res(net.res_line, line_idx, "q_from_mvar") if hasattr(net, "res_line") else np.nan
            p_to = _safe_res(net.res_line, line_idx, "p_to_mw") if hasattr(net, "res_line") else np.nan
            q_to = _safe_res(net.res_line, line_idx, "q_to_mvar") if hasattr(net, "res_line") else np.nan
            pl_mw = _safe_res(net.res_line, line_idx, "pl_mw") if hasattr(net, "res_line") else np.nan

            hover_text = (
                f"<b>{panel_name} | Line {line_idx}</b><br>"
                f"Name: {row.get('name', '')}<br>"
                f"From bus: {row['from_bus']}<br>"
                f"To bus: {row['to_bus']}<br>"
                f"Loading: {_fmt(loading, 2)}%<br>"
                f"P from: {_fmt(p_from, 3)} MW | Q from: {_fmt(q_from, 3)} MVAr<br>"
                f"P to: {_fmt(p_to, 3)} MW | Q to: {_fmt(q_to, 3)} MVAr<br>"
                f"Active losses: {_fmt(pl_mw, 4)} MW"
            )

            traces.append(
                go.Scatter(
                    x=[xy1[0], xy2[0]],
                    y=[xy1[1], xy2[1]],
                    mode="lines",
                    line=dict(color=_line_loading_color(loading), width=line_width),
                    hoverinfo="skip",
                    name="Branch loading",
                    showlegend=False,
                )
            )

            # Dedicated invisible hover trace. This keeps the visible network crisp
            # while still making it easy to inspect line information with the mouse.
            mid_x = (xy1[0] + xy2[0]) / 2
            mid_y = (xy1[1] + xy2[1]) / 2
            traces.append(
                go.Scatter(
                    x=[xy1[0], mid_x, xy2[0]],
                    y=[xy1[1], mid_y, xy2[1]],
                    mode="lines",
                    line=dict(color="rgba(0,0,0,0.001)", width=max(10, line_width * 3)),
                    hovertemplate=hover_text + "<extra></extra>",
                    name="Line hover",
                    showlegend=False,
                )
            )

    # Retain primary-substation supply
    # links and closed busbar couplers in every pre/post slider state.
    for ext_idx, bus, source_xy, bus_xy in _external_grid_stubs(net):
        traces.append(go.Scatter(
            x=[source_xy[0], bus_xy[0]], y=[source_xy[1], bus_xy[1]],
            mode="lines+markers",
            line=dict(color="#7c3aed", width=3.6),
            marker=dict(size=[13, 0], symbol=["star", "circle"], color="#7c3aed"),
            hovertemplate=(
                f"<b>{panel_name} | Primary substation {ext_idx}</b><br>"
                f"Connected bus: {bus}<extra></extra>"
            ),
            name="Primary substation supply",
            showlegend=bool(show_legend_items),
        ))

    for switch_idx, row in _closed_bus_couplers(net):
        xy1 = _xy(row["bus"])
        xy2 = _xy(row["element"])
        if xy1 is None or xy2 is None:
            continue
        traces.append(go.Scatter(
            x=[xy1[0], xy2[0]], y=[xy1[1], xy2[1]], mode="lines",
            line=dict(color="#db2777", width=2.6, dash="dot"),
            hovertemplate=(
                f"<b>{panel_name} | Closed bus coupler {switch_idx}</b><br>"
                f"Bus {row['bus']} to bus {row['element']}<extra></extra>"
            ),
            name="Closed substation bus coupler",
            showlegend=bool(show_legend_items),
        ))

    # Two-winding transformers.
    if hasattr(net, "trafo") and not net.trafo.empty:
        for trafo_idx, row in net.trafo.iterrows():
            xy1 = _xy(row["hv_bus"])
            xy2 = _xy(row["lv_bus"])
            if xy1 is None or xy2 is None:
                continue
            loading = _safe_res(net.res_trafo, trafo_idx, "loading_percent") if hasattr(net, "res_trafo") else np.nan
            hover_text = (
                f"<b>{panel_name} | Transformer {trafo_idx}</b><br>"
                f"Name: {row.get('name', '')}<br>"
                f"HV bus: {row['hv_bus']}<br>LV bus: {row['lv_bus']}<br>"
                f"Loading: {_fmt(loading, 2)}%"
            )
            traces.append(
                go.Scatter(
                    x=[xy1[0], xy2[0]],
                    y=[xy1[1], xy2[1]],
                    mode="lines",
                    line=dict(color="#475569", width=max(2.4, line_width - 0.4), dash="dash"),
                    hovertemplate=hover_text + "<extra></extra>",
                    name="Transformer",
                    showlegend=False,
                )
            )

    # Three-winding transformers.
    if hasattr(net, "trafo3w") and not net.trafo3w.empty:
        for trafo_idx, row in net.trafo3w.iterrows():
            loading = _safe_res(net.res_trafo3w, trafo_idx, "loading_percent") if hasattr(net, "res_trafo3w") else np.nan
            for bus_a, bus_b in [("hv_bus", "mv_bus"), ("hv_bus", "lv_bus"), ("mv_bus", "lv_bus")]:
                if bus_a not in row.index or bus_b not in row.index:
                    continue
                xy1 = _xy(row[bus_a])
                xy2 = _xy(row[bus_b])
                if xy1 is None or xy2 is None:
                    continue
                hover_text = (
                    f"<b>{panel_name} | Three-winding transformer {trafo_idx}</b><br>"
                    f"Name: {row.get('name', '')}<br>"
                    f"{bus_a}: {row[bus_a]}<br>{bus_b}: {row[bus_b]}<br>"
                    f"Loading: {_fmt(loading, 2)}%"
                )
                traces.append(
                    go.Scatter(
                        x=[xy1[0], xy2[0]],
                        y=[xy1[1], xy2[1]],
                        mode="lines",
                        line=dict(color="#475569", width=2.4, dash="dash"),
                        hovertemplate=hover_text + "<extra></extra>",
                        name="3W transformer",
                        showlegend=False,
                    )
                )

    # Buses.
    bus_x, bus_y, bus_text, bus_vm, bus_label = [], [], [], [], []
    for bus_idx, row in net.bus.iterrows():
        xy = _xy(bus_idx)
        if xy is None:
            continue
        vm_pu = _safe_res(net.res_bus, bus_idx, "vm_pu") if hasattr(net, "res_bus") else np.nan
        p_mw = _safe_res(net.res_bus, bus_idx, "p_mw") if hasattr(net, "res_bus") else np.nan
        q_mvar = _safe_res(net.res_bus, bus_idx, "q_mvar") if hasattr(net, "res_bus") else np.nan
        bus_x.append(xy[0])
        bus_y.append(xy[1])
        bus_label.append(str(bus_idx))
        bus_vm.append(vm_pu)
        bus_text.append(
            f"<b>{panel_name} | Bus {bus_idx}</b><br>"
            f"Name: {row.get('name', '')}<br>"
            f"Voltage level: {row.get('vn_kv', '')} kV<br>"
            f"Voltage: {_fmt(vm_pu, 4)} pu<br>"
            f"P injection: {_fmt(p_mw, 3)} MW<br>"
            f"Q injection: {_fmt(q_mvar, 3)} MVAr"
        )

    traces.append(
        go.Scatter(
            x=bus_x,
            y=bus_y,
            mode="markers+text",
            marker=dict(
                size=bus_size,
                color=bus_vm,
                colorscale=cmap,
                cmin=0.95,
                cmax=1.05,
                showscale=False,
                opacity=0.98,
                line=dict(color="#ffffff", width=1.4),
            ),
            text=bus_label,
            textposition="middle center",
            textfont=dict(size=9, color="#ffffff"),
            hovertemplate="%{hovertext}<extra></extra>" if show_bus_hover else None,
            hovertext=bus_text if show_bus_hover else None,
            hoverinfo="text" if show_bus_hover else "skip",
            name=f"{panel_name} buses",
            showlegend=False,
        )
    )

    if show_legend_items:
        legend_items = [
            ("Line < 80%", "rgba(120,140,160,0.65)"),
            ("80% <= line < 97%", "rgba(44,160,44,0.85)"),
            ("97% <= line < 100%", "rgba(255,127,14,0.95)"),
            ("Line >= 100%", "rgba(214,39,40,0.95)"),
        ]
        for label, color in legend_items:
            traces.append(
                go.Scatter(
                    x=[None],
                    y=[None],
                    mode="lines",
                    line=dict(color=color, width=5),
                    name=label,
                    showlegend=True,
                )
            )

    return traces


def _make_pre_post_nets_for_hour(net, ts_res, post_market_folder, hour):
    """Return pre-market and post-market network copies for one hour."""
    pre_net = cp.deepcopy(net)
    pre_net = _apply_time_step_to_net(pre_net, ts_res, int(hour))
    try:
        pp.runpp(pre_net)
    except Exception as exc:
        print(f"WARNING: pre-market power flow failed for hour {hour}: {exc}")

    post_net = cp.deepcopy(net)
    post_net = _apply_post_market_results_from_folder(post_net, post_market_folder, int(hour))
    try:
        pp.runpp(post_net)
    except Exception as exc:
        print(f"WARNING: post-market power flow failed for hour {hour}: {exc}")

    return pre_net, post_net


