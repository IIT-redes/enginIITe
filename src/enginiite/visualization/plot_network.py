def _available_topology_hours(ts_res=None, post_market_folder=None):
    """
    Return sorted hours that can safely be used for the all-hours topology slider.

    Important design choice:
        The slider must use the INTERSECTION of hours available in both the
        pre-market time-series data and the post-market CSV files.

    Why:
        The pre-market simulation usually has 24 hours, but the post-market
        validation is normally run only for the studied/market-cleared hours.
        If the slider uses the union of hours, it can request a post-market
        hour that is not present in files such as res_load/p_mw.csv and crash.
    """

    def _hours_from_index(index):
        out = set()
        for idx in index:
            try:
                out.add(int(idx))
            except Exception:
                try:
                    out.add(int(float(str(idx).strip())))
                except Exception:
                    pass
        return out

    pre_hours = set()
    if isinstance(ts_res, dict):
        for df in ts_res.values():
            if isinstance(df, pd.DataFrame) and len(df.index) > 0:
                pre_hours |= _hours_from_index(df.index)

    post_hour_sets = []
    if post_market_folder is not None and os.path.exists(post_market_folder):
        candidates = [
            os.path.join(post_market_folder, "res_bus", "vm_pu.csv"),
            os.path.join(post_market_folder, "res_line", "loading_percent.csv"),
            os.path.join(post_market_folder, "res_trafo", "loading_percent.csv"),
            os.path.join(post_market_folder, "res_trafo3w", "loading_percent.csv"),
            os.path.join(post_market_folder, "res_load", "p_mw.csv"),
            os.path.join(post_market_folder, "res_load", "q_mvar.csv"),
            os.path.join(post_market_folder, "res_sgen", "p_mw.csv"),
            os.path.join(post_market_folder, "res_sgen", "q_mvar.csv"),
            os.path.join(post_market_folder, "res_storage", "p_mw.csv"),
            os.path.join(post_market_folder, "res_storage", "q_mvar.csv"),
        ]
        for path in candidates:
            if os.path.exists(path):
                try:
                    df = pd.read_csv(path, index_col=0)
                    hset = _hours_from_index(df.index)
                    if hset:
                        post_hour_sets.append(hset)
                except Exception:
                    pass

    post_hours = set.intersection(*post_hour_sets) if post_hour_sets else set()

    if pre_hours and post_hours:
        return sorted(pre_hours & post_hours)
    if post_hours:
        return sorted(post_hours)
    if pre_hours:
        return sorted(pre_hours)
    return []

