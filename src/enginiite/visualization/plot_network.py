def _apply_time_step_to_net(net, ts_res, hour):
    """
    Apply pre-market time-series values to a copied pandapower network.

    Parameters
    ----------
    net : pandapowerNet
        Network copy to modify.

    ts_res : dict
        Time-series result dictionary from rnet.run_pf_timeseries().

    hour : int
        Selected hour from the YAML config.

    Returns
    -------
    pandapowerNet
        Network with P/Q values updated for the selected hour.
    """

    hour = int(hour)

    def _get_df(possible_keys):
        """Return the first dataframe found in ts_res using possible key names."""
        for key in possible_keys:
            if key in ts_res:
                return ts_res[key]
        return None

    def _apply_df_to_element(element_name, column_name, df):
        """Apply one time-series dataframe to one pandapower element column."""

        if df is None:
            return

        if not hasattr(net, element_name):
            return

        element_df = getattr(net, element_name)

        if element_df.empty:
            return

        # Find the selected hour either by index value or by row position.
        if hour in df.index:
            row = df.loc[hour]
        elif str(hour) in df.index:
            row = df.loc[str(hour)]
        elif hour < len(df):
            row = df.iloc[hour]
        else:
            raise ValueError(
                f"Hour {hour} was not found in time-series dataframe for {element_name}.{column_name}"
            )

        # Write values to the pandapower element table.
        for idx in element_df.index:
            if idx in row.index:
                element_df.loc[idx, column_name] = row[idx]
            elif str(idx) in row.index:
                element_df.loc[idx, column_name] = row[str(idx)]

    # Try several possible key names to be robust to platform naming differences.
    load_p = _get_df(["load_p", "res_load_p", "p_load", "load_p_mw", "load_p_mw"])
    load_q = _get_df(["load_q", "res_load_q", "q_load", "load_q_mvar"])
    sgen_p = _get_df(["sgen_p", "res_sgen_p", "p_sgen", "sgen_p_mw"])
    sgen_q = _get_df(["sgen_q", "res_sgen_q", "q_sgen", "sgen_q_mvar"])
    storage_p = _get_df(["storage_p", "res_storage_p", "p_storage", "storage_p_mw"])
    storage_q = _get_df(["storage_q", "res_storage_q", "q_storage", "storage_q_mvar"])

    _apply_df_to_element("load", "p_mw", load_p)
    _apply_df_to_element("load", "q_mvar", load_q)
    _apply_df_to_element("sgen", "p_mw", sgen_p)
    _apply_df_to_element("sgen", "q_mvar", sgen_q)
    _apply_df_to_element("storage", "p_mw", storage_p)
    _apply_df_to_element("storage", "q_mvar", storage_q)

    # The supply voltage may change per time step
    # (ext_grid profile); the logged voltage of the ext_grid bus is that step's set-point.
    bus_vm = _get_df(["bus_vm_pu", "bus_vm", "res_bus_vm_pu"])
    if bus_vm is not None:
        if hour in bus_vm.index:
            _apply_ext_grid_vm_from_bus_row(net, bus_vm.loc[hour])
        elif str(hour) in bus_vm.index:
            _apply_ext_grid_vm_from_bus_row(net, bus_vm.loc[str(hour)])

    return net


def _apply_ext_grid_vm_from_bus_row(net, bus_row):
    """
    Set every ext_grid set-point to the logged voltage of
    its bus in one time step (bus_row: Series indexed by bus, as int or str).
    """
    if not hasattr(net, "ext_grid") or net.ext_grid.empty:
        return
    for idx, bus in net.ext_grid.bus.items():
        for key in (int(bus), str(int(bus))):
            if key in bus_row.index and pd.notna(bus_row[key]):
                net.ext_grid.at[idx, "vm_pu"] = float(bus_row[key])
                break



def _read_post_market_csv(folder, element, variable):
    """
    Read one post-market result CSV file.

    Example path created by this helper:
        <folder>/res_load/p_mw.csv
        <folder>/res_sgen/q_mvar.csv

    Returns None if the file does not exist.
    """

    path = os.path.join(folder, f"res_{element}", f"{variable}.csv")

    if not os.path.exists(path):
        return None

    return pd.read_csv(path, index_col=0)



def _apply_post_market_results_from_folder(net, post_folder, hour):
    """
    Apply post-market saved CSV values to a copied pandapower network.

    This function is used for post-market HTML plots. The post-market time-series
    results are already saved in output_ts_root by rnet.run_pf_timeseries().
    """

    hour = int(hour)

    # Mapping format:
    #   (pandapower element table, pandapower column to update, CSV filename)
    mapping = [
        ("load", "p_mw", "p_mw"),
        ("load", "q_mvar", "q_mvar"),
        ("sgen", "p_mw", "p_mw"),
        ("sgen", "q_mvar", "q_mvar"),
        ("storage", "p_mw", "p_mw"),
        ("storage", "q_mvar", "q_mvar"),
    ]

    for element, net_col, csv_name in mapping:
        df = _read_post_market_csv(post_folder, element, csv_name)

        if df is None:
            continue

        if not hasattr(net, element):
            continue

        element_df = getattr(net, element)

        if element_df.empty:
            continue

        # Use exact hour labels only. Post-market CSV files normally use the
        # original studied-hour numbers as their index, e.g. [0, ..., 14, 17, 18, 19, 20].
        # Positional fallback such as df.iloc[hour] is unsafe here because it can
        # silently map hour 17 to the wrong row when skipped hours exist.
        if hour in df.index:
            row = df.loc[hour]
        elif str(hour) in df.index:
            row = df.loc[str(hour)]
        else:
            numeric_index = pd.to_numeric(df.index, errors="coerce")
            matches = np.where(numeric_index == hour)[0]
            if len(matches) > 0:
                row = df.iloc[int(matches[0])]
            else:
                available = []
                for idx in df.index:
                    try:
                        available.append(int(idx))
                    except Exception:
                        pass
                raise ValueError(
                    f"Hour {hour} was not found in post-market CSV for {element}/{csv_name}. "
                    f"Available hours: {available[:30]}"
                )

        for idx in element_df.index:
            if idx in row.index:
                element_df.loc[idx, net_col] = row[idx]
            elif str(idx) in row.index:
                element_df.loc[idx, net_col] = row[str(idx)]

    # Supply voltage of this time step (see
    # _apply_ext_grid_vm_from_bus_row); the post-market folder logs res_bus/vm_pu.csv.
    bus_vm = _read_post_market_csv(post_folder, "bus", "vm_pu")
    if bus_vm is not None:
        numeric_index = pd.to_numeric(bus_vm.index, errors="coerce")
        matches = np.where(numeric_index == hour)[0]
        if len(matches) > 0:
            _apply_ext_grid_vm_from_bus_row(net, bus_vm.iloc[int(matches[0])])

    return net


