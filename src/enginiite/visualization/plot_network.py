"""
plot_network.py
================

Visualization utilities for the enginIITe platform.

This file is designed to live here:

    enginiite/visualization/plot_network.py

All figures generated by this file are saved inside a dedicated subfolder:

    <scenario_specific_visualization_folder>/network_topology/

It provides two complementary visualization layers:

1. Interactive HTML topology plots, saved with Plotly.
   Static PNG/PDF/SVG exports are intentionally disabled in the current
   visualization workflow to keep one clean scenario-specific HTML output tree.

2. Interactive HTML plots, saved with Plotly.
   These are useful for inspecting bus voltages, line loading, line power flow,
   transformer loading, and FSP locations by hovering with the mouse.

The functions are intentionally modular and beginner-friendly:

- Helper functions start with an underscore, for example _get_bus_xy().
- Public functions are called from main.py, for example:
      plot_network_topology_with_fsp(...)
      plot_network_topology_with_fsp_html(...)
      plot_pre_market_hour_html(...)
      plot_post_market_hour_html_from_folder(...)

Important modelling context:

- net is a pandapower network.
- net.bus_geodata is used for coordinates.
- fsp_data is the FSP dataframe imported by the platform.
- FSP type convention is:
      A = load FSP
      B = generator/static generator FSP
      C = storage FSP

Single-output policy
--------------------
All figures generated by this module are saved only inside the
scenario-specific visualization folder passed as output_folder.
Group-level visualization folders are intentionally blocked.
Do not pass a generic country-level visualization folder as a second
common_output_folder. The common_output_folder argument is kept only
for backward compatibility and is intentionally ignored.
"""

