def plot_network_topology_with_fsp_html(
    net,
    fsp_data=None,
    output_folder=None,
    filename="network_topology_fsp_locations",
    title="Network Topology and FSP Locations",
    market_tag=None,
):
    """
    Create an interactive HTML topology plot with FSP hover labels.

    This plot is not hour-specific. It shows the initial network structure and
    FSP locations. It is useful for zooming and checking resource placement.

    Unlike the pre/post-market power-flow plots, this function does not run a
    power flow and does not show voltage/loading results.
    """
    _apply_radial_single_line_layout(net)

    # Save inside the dedicated topology subfolder of the scenario-specific visualization folder.
    inferred_market_tag = market_tag or _extract_market_tag_from_text(filename) or _extract_market_tag_from_text(title)
    output_folder = _get_network_plot_output_folder(output_folder, market_tag=inferred_market_tag)

    fig = go.Figure()
    used_branch_labels = set()

    # ------------------------------------------------------------------
    # 1. Lines
    # ------------------------------------------------------------------
    if hasattr(net, "line") and not net.line.empty:
        for line_idx, row in net.line.iterrows():
            if not _line_is_operational(net, line_idx, row):
                continue
            xy1 = _get_bus_xy(net, row["from_bus"])
            xy2 = _get_bus_xy(net, row["to_bus"])
            if xy1 is None or xy2 is None:
                continue
            branch_color, branch_label = _branch_voltage_style(
                net, row["from_bus"], row["to_bus"]
            )

            fig.add_trace(
                go.Scatter(
                    x=[xy1[0], xy2[0]],
                    y=[xy1[1], xy2[1]],
                    mode="lines",
                    line=dict(color=branch_color, width=2.5),
                    hoverinfo="text",
                    hovertext=(
                        f"<b>Line {line_idx}</b><br>"
                        f"Name: {row.get('name', '')}<br>"
                        f"From bus: {row['from_bus']}<br>"
                        f"To bus: {row['to_bus']}"
                    ),
                    name=branch_label,
                    legendgroup=branch_label,
                    showlegend=branch_label not in used_branch_labels,
                )
            )
            used_branch_labels.add(branch_label)

    # ------------------------------------------------------------------
    # 2. Primary-substation supplies, bus couplers, and transformers
    # ------------------------------------------------------------------
    for ext_idx, bus, source_xy, bus_xy in _external_grid_stubs(net):
        label = "Primary substation supply"
        fig.add_trace(go.Scatter(
            x=[source_xy[0], bus_xy[0]], y=[source_xy[1], bus_xy[1]],
            mode="lines+markers",
            line=dict(color="#7c3aed", width=4),
            marker=dict(size=[15, 0], symbol=["star", "circle"], color="#7c3aed"),
            hovertemplate=(
                f"<b>Primary substation {ext_idx}</b><br>"
                f"Connected network bus: {bus}<extra></extra>"
            ),
            name=label, legendgroup=label,
            showlegend=label not in used_branch_labels,
        ))
        used_branch_labels.add(label)

    for switch_idx, row in _closed_bus_couplers(net):
        xy1 = _get_bus_xy(net, row["bus"])
        xy2 = _get_bus_xy(net, row["element"])
        if xy1 is None or xy2 is None:
            continue
        label = "Closed substation bus coupler"
        fig.add_trace(go.Scatter(
            x=[xy1[0], xy2[0]], y=[xy1[1], xy2[1]], mode="lines",
            line=dict(color="#db2777", width=3, dash="dot"),
            hovertemplate=(
                f"<b>Closed bus coupler {switch_idx}</b><br>"
                f"Bus {row['bus']} to bus {row['element']}<extra></extra>"
            ),
            name=label, legendgroup=label,
            showlegend=label not in used_branch_labels,
        ))
        used_branch_labels.add(label)

    if hasattr(net, "trafo") and not net.trafo.empty:
        for trafo_idx, row in net.trafo.iterrows():
            if not bool(row.get("in_service", True)):
                continue
            xy1 = _get_bus_xy(net, row["hv_bus"])
            xy2 = _get_bus_xy(net, row["lv_bus"])
            if xy1 is None or xy2 is None:
                continue
            label = "Transformer between voltage levels"
            fig.add_trace(go.Scatter(
                x=[xy1[0], xy2[0]], y=[xy1[1], xy2[1]], mode="lines",
                line=dict(color="#334155", width=3, dash="dash"),
                hovertemplate=(
                    f"<b>Transformer {trafo_idx}</b><br>"
                    f"Name: {row.get('name', '')}<br>"
                    f"HV bus: {row['hv_bus']}<br>LV bus: {row['lv_bus']}<extra></extra>"
                ),
                name=label, legendgroup=label,
                showlegend=label not in used_branch_labels,
            ))
            used_branch_labels.add(label)

    # Three-winding transformers.
    if hasattr(net, "trafo3w") and not net.trafo3w.empty:
        for trafo_idx, row in net.trafo3w.iterrows():
            for bus_a, bus_b in [("hv_bus", "mv_bus"), ("hv_bus", "lv_bus"), ("mv_bus", "lv_bus")]:
                xy1 = _get_bus_xy(net, row[bus_a])
                xy2 = _get_bus_xy(net, row[bus_b])
                if xy1 is None or xy2 is None:
                    continue

                fig.add_trace(
                    go.Scatter(
                        x=[xy1[0], xy2[0]],
                        y=[xy1[1], xy2[1]],
                        mode="lines",
                        line=dict(color="rgba(52,73,94,0.75)", width=2, dash="dash"),
                        hoverinfo="text",
                        hovertext=(
                            f"<b>Trafo3W {trafo_idx}</b><br>"
                            f"{bus_a}: {row[bus_a]}<br>"
                            f"{bus_b}: {row[bus_b]}"
                        ),
                        name="Three-winding transformer",
                        legendgroup="Three-winding transformer",
                        showlegend="Three-winding transformer" not in used_branch_labels,
                    )
                )
                used_branch_labels.add("Three-winding transformer")

    # ------------------------------------------------------------------
    # 3. Buses
    # ------------------------------------------------------------------
    bus_x, bus_y, bus_hover, bus_color, bus_size, bus_text = [], [], [], [], [], []

    for bus_idx, row in net.bus.iterrows():
        xy = _get_bus_xy(net, bus_idx)
        if xy is None:
            continue

        bus_x.append(xy[0])
        bus_y.append(xy[1])
        bus_text.append(str(bus_idx))

        vn_kv = row.get("vn_kv", "")
        name = row.get("name", "")

        bus_hover.append(f"<b>Bus {bus_idx}</b><br>Name: {name}<br>Vn: {vn_kv} kV")

        # Use voltage-level-specific colors.
        if np.isclose(float(vn_kv), 110.0):
            bus_color.append("#003A70")
            bus_size.append(14)
        elif np.isclose(float(vn_kv), 30.0):
            bus_color.append("#007C89")
            bus_size.append(11)
        elif np.isclose(float(vn_kv), 15.0):
            bus_color.append("#5e60ce")
            bus_size.append(9)
        else:
            bus_color.append("#555555")
            bus_size.append(8)

    fig.add_trace(
        go.Scatter(
            x=bus_x,
            y=bus_y,
            mode="markers+text",
            marker=dict(size=bus_size, color=bus_color, line=dict(color="white", width=1)),
            text=bus_text,
            textposition="middle center",
            textfont=dict(size=9, color="white"),
            hoverinfo="text",
            hovertext=bus_hover,
            name="Buses",
        )
    )

    # ------------------------------------------------------------------
    # 4. FSP resource markers
    # ------------------------------------------------------------------
    if fsp_data is not None and not fsp_data.empty:
        type_style = {
            "A": {"name": "Load FSP", "symbol": "square", "color": "#f39c12"},
            "B": {"name": "Generator FSP", "symbol": "triangle-up", "color": "#2ecc71"},
            "C": {"name": "Storage FSP", "symbol": "diamond", "color": "#8e44ad"},
        }

        for fsp_type, style in type_style.items():
            sub = fsp_data[fsp_data["type"].astype(str).str.strip() == fsp_type]

            xs, ys, hover = [], [], []

            for _, row in sub.iterrows():
                xy = _get_bus_xy(net, int(row["bus"]))
                if xy is None:
                    continue

                xs.append(xy[0])
                ys.append(xy[1])

                hover.append(
                    f"<b>{style['name']}</b><br>"
                    f"ID: {row.get('id', '')}<br>"
                    f"Name: {row.get('name', '')}<br>"
                    f"Bus: {row.get('bus', '')}<br>"
                    f"MVA: {row.get('mva', '')}"
                )

            fig.add_trace(
                go.Scatter(
                    x=xs,
                    y=ys,
                    mode="markers",
                    marker=dict(
                        size=17,
                        color=style["color"],
                        symbol=style["symbol"],
                        line=dict(color="black", width=1),
                    ),
                    hoverinfo="text",
                    hovertext=hover,
                    name=style["name"],
                )
            )

    # ------------------------------------------------------------------
    # 5. Layout and save
    # ------------------------------------------------------------------
    fig.update_layout(
        title=title,
        width=1200,
        height=800,
        xaxis_title="Electrical depth from primary substation",
        yaxis_title="Radial branch order",
        legend=dict(
            x=0.01, y=0.99, bgcolor="rgba(255,255,255,0.92)",
            bordercolor="rgba(148,163,184,0.5)", borderwidth=1,
        ),
        hovermode="closest",
    )

    fig.update_yaxes(scaleanchor="x", scaleratio=1)

    html_path = _write_plotly_html(
        fig,
        output_folder,
        filename + ".html",
        market_tag=inferred_market_tag,
    )

    return fig


