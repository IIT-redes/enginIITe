def plot_network_topology_with_fsp(
    net,
    fsp_data=None,
    output_folder=None,
    filename="network_topology_fsp_locations",
    title="Network Topology and Flexibility Resource Locations",
    label_mode="compact",
    show_bus_labels=True,
    show_resource_table=False,
    save_png=False,
    save_pdf=False,
    save_svg=False,
    dpi=300,
    market_tag=None,
):
    """
    Create a static network topology plot with FSP locations.

    This is the recommended figure for reports and slides.

    Parameters
    ----------
    net : pandapowerNet
        Pandapower network.

    fsp_data : pandas.DataFrame or None
        FSP dataframe imported by enginIITe. If None, only the network topology
        is plotted.

    output_folder : str or None
        Folder where the plot files are saved. If None, current directory is used.

    filename : str
        Output name without extension.

    title : str
        Plot title.

    label_mode : str
        'none'    -> no FSP labels on map.
        'compact' -> compact bus-level labels such as A, B, C, A/B/C.
        'full'    -> shortened FSP IDs, useful for debugging but may overlap.

    show_bus_labels : bool
        If True, bus numbers are written inside bus markers.

    show_resource_table : bool
        If True, adds a table to the right side. For clean slides, False is better.

    save_png, save_pdf, save_svg : bool
        Output format switches.

    dpi : int
        PNG resolution.

    Returns
    -------
    fig, ax
        Matplotlib figure and axis.
    """

    # Use one radial layout and expose
    # primary-substation, bus-coupler, transformer and voltage-level branches.
    _apply_radial_single_line_layout(net)

    # Save all topology figures inside:
    #     <current visualization folder>/network_topology/
    # This keeps the scenario results organized and avoids saving the same plot
    # in several unrelated places.
    inferred_market_tag = market_tag or _extract_market_tag_from_text(filename) or _extract_market_tag_from_text(title)
    output_folder = _get_network_plot_output_folder(output_folder, market_tag=inferred_market_tag)

    # Static plot requires bus coordinates.
    if not hasattr(net, "bus_geodata") or net.bus_geodata.empty:
        raise ValueError("net.bus_geodata is empty. The topology plot needs bus coordinates.")

    # Create a large figure to keep labels readable.
    fig, ax = plt.subplots(figsize=(16, 10))

    ax.set_title(title, fontsize=18, fontweight="bold", pad=16)

    # ------------------------------------------------------------------
    # 1. Draw network lines
    # ------------------------------------------------------------------
    used_branch_labels = set()
    if hasattr(net, "line") and not net.line.empty:
        for line_idx, row in net.line.iterrows():
            if not _line_is_operational(net, line_idx, row):
                continue
            branch_color, branch_label = _branch_voltage_style(
                net, row["from_bus"], row["to_bus"]
            )
            _plot_branch(
                ax=ax,
                net=net,
                from_bus=row["from_bus"],
                to_bus=row["to_bus"],
                color=branch_color,
                linewidth=2.1,
                linestyle="-",
                alpha=0.75,
                zorder=1,
            )
            if branch_label not in used_branch_labels:
                ax.plot([], [], color=branch_color, linewidth=2.1, label=branch_label)
                used_branch_labels.add(branch_label)

    # Primary-substation supply stubs and substation bus couplers.
    for _, bus, source_xy, bus_xy in _external_grid_stubs(net):
        ax.plot(
            [source_xy[0], bus_xy[0]], [source_xy[1], bus_xy[1]],
            color="#7c3aed", linewidth=3.0, zorder=3,
            label="Primary substation supply" if "Primary substation supply" not in used_branch_labels else None,
        )
        used_branch_labels.add("Primary substation supply")
        ax.scatter(
            source_xy[0], source_xy[1], s=180, marker="*", color="#7c3aed",
            edgecolor="white", linewidth=1.1, zorder=12,
        )

    for _, row in _closed_bus_couplers(net):
        _plot_branch(
            ax, net, row["bus"], row["element"], "#db2777", 2.6,
            linestyle=":", alpha=0.9, zorder=3,
        )
        if "Closed substation bus coupler" not in used_branch_labels:
            ax.plot([], [], color="#db2777", linewidth=2.6, linestyle=":",
                    label="Closed substation bus coupler")
            used_branch_labels.add("Closed substation bus coupler")

    # ------------------------------------------------------------------
    # 2. Draw two-winding transformers
    # ------------------------------------------------------------------
    if hasattr(net, "trafo") and not net.trafo.empty:
        for _, row in net.trafo.iterrows():
            _plot_branch(
                ax=ax,
                net=net,
                from_bus=row["hv_bus"],
                to_bus=row["lv_bus"],
                color="#34495e",
                linewidth=2.3,
                linestyle="--",
                alpha=0.75,
                zorder=2,
            )
        ax.plot([], [], color="#34495e", linewidth=2.3, linestyle="--",
                label="Transformer between voltage levels")

    # ------------------------------------------------------------------
    # 3. Draw three-winding transformers
    # ------------------------------------------------------------------
    if hasattr(net, "trafo3w") and not net.trafo3w.empty:
        for _, row in net.trafo3w.iterrows():
            # A 3-winding transformer is represented by branches between HV, MV, LV buses.
            for bus_a, bus_b in [("hv_bus", "mv_bus"), ("hv_bus", "lv_bus"), ("mv_bus", "lv_bus")]:
                if bus_a in row.index and bus_b in row.index:
                    _plot_branch(
                        ax=ax,
                        net=net,
                        from_bus=row[bus_a],
                        to_bus=row[bus_b],
                        color="#34495e",
                        linewidth=2.0,
                        linestyle="--",
                        alpha=0.70,
                        zorder=2,
                    )

    # ------------------------------------------------------------------
    # 4. Draw buses by voltage level
    # ------------------------------------------------------------------
    voltage_styles = {
        110.0: {"color": "#003A70", "size": 200, "label": "110 kV bus"},
        30.0: {"color": "#007C89", "size": 140, "label": "30 kV bus"},
        15.0: {"color": "#5e60ce", "size": 105, "label": "15 kV bus"},
    }

    # Keep track of legend labels already used, so each appears only once.
    used_bus_labels = set()

    for bus_idx, row in net.bus.iterrows():
        xy = _get_bus_xy(net, bus_idx)

        # Skip buses without coordinates.
        if xy is None:
            continue

        x, y = xy
        vn_kv = float(row.get("vn_kv", np.nan))

        # Default style for unknown voltage levels.
        style = {"color": "#555555", "size": 90, "label": "other bus"}

        # Select style based on voltage level.
        for voltage, candidate_style in voltage_styles.items():
            if np.isclose(vn_kv, voltage):
                style = candidate_style
                break

        # Add legend entry only once per voltage class.
        legend_label = None
        if style["label"] not in used_bus_labels:
            legend_label = style["label"]
            used_bus_labels.add(style["label"])

        ax.scatter(
            x,
            y,
            s=style["size"],
            color=style["color"],
            edgecolor="white",
            linewidth=1.3,
            zorder=10,
            label=legend_label,
        )

        # Optionally write bus index inside the bus marker.
        if show_bus_labels:
            ax.text(
                x,
                y,
                str(bus_idx),
                fontsize=8,
                color="white",
                ha="center",
                va="center",
                fontweight="bold",
                zorder=11,
            )

    # ------------------------------------------------------------------
    # 5. Draw FSP markers
    # ------------------------------------------------------------------
    fsp_by_bus = _prepare_fsp_by_bus(fsp_data)

    # Color convention for resource types.
    resource_color = {
        "A": "#f39c12",  # load FSP
        "B": "#2ecc71",  # generator FSP
        "C": "#8e44ad",  # storage FSP
    }

    # Marker-shape convention for resource types.
    resource_marker = {
        "A": "s",  # square for load
        "B": "^",  # triangle for generator
        "C": "D",  # diamond for storage
    }

    # Legend names for resource types.
    resource_label = {
        "A": "Load FSP",
        "B": "Generator FSP",
        "C": "Storage FSP",
    }

    # Keep track of resource labels already added to legend.
    used_resource_labels = set()

    # Small offsets avoid exact overlap when multiple resource types are at one bus.
    offset_by_type = {
        "A": (-0.006, -0.006),
        "B": (0.006, 0.006),
        "C": (0.010, -0.010),
    }

    if fsp_data is not None and not fsp_data.empty:
        for _, row in fsp_data.iterrows():
            fsp_bus = int(row["bus"])
            fsp_type = str(row["type"]).strip()

            xy = _get_bus_xy(net, fsp_bus)
            if xy is None:
                continue

            x, y = xy
            dx, dy = offset_by_type.get(fsp_type, (0.0, 0.0))

            # Add each resource type to legend only once.
            legend_label = None
            if resource_label.get(fsp_type, "Other FSP") not in used_resource_labels:
                legend_label = resource_label.get(fsp_type, "Other FSP")
                used_resource_labels.add(legend_label)

            ax.scatter(
                x + dx,
                y + dy,
                s=260,
                marker=resource_marker.get(fsp_type, "o"),
                color=resource_color.get(fsp_type, "#000000"),
                edgecolor="black",
                linewidth=0.8,
                alpha=0.95,
                zorder=30,
                label=legend_label,
            )

        # Compact labels show only resource types at each bus, for example A/B/C.
        if label_mode == "compact":
            for bus, info in fsp_by_bus.items():
                xy = _get_bus_xy(net, bus)
                if xy is None:
                    continue

                x, y = xy
                compact = "/".join(sorted(set(info["types"])))

                ax.text(
                    x,
                    y + 0.018,
                    compact,
                    fontsize=9,
                    fontweight="bold",
                    color="#1b1b1b",
                    ha="center",
                    va="bottom",
                    bbox=dict(
                        boxstyle="round,pad=0.22",
                        facecolor="white",
                        edgecolor="#007C89",
                        linewidth=0.9,
                        alpha=0.92,
                    ),
                    zorder=35,
                )

        # Full labels show shortened FSP IDs. Useful for debugging but may overlap.
        elif label_mode == "full":
            for _, row in fsp_data.iterrows():
                fsp_bus = int(row["bus"])
                xy = _get_bus_xy(net, fsp_bus)
                if xy is None:
                    continue

                x, y = xy
                label = row["id"] if "id" in fsp_data.columns and pd.notna(row.get("id")) else row.get("name", "FSP")

                ax.text(
                    x,
                    y + 0.016,
                    _short_label(label, 14),
                    fontsize=7,
                    color="#1b1b1b",
                    ha="center",
                    va="bottom",
                    bbox=dict(
                        boxstyle="round,pad=0.18",
                        facecolor="white",
                        edgecolor="#999999",
                        linewidth=0.7,
                        alpha=0.88,
                    ),
                    zorder=35,
                )

    # ------------------------------------------------------------------
    # 6. Optional resource table
    # ------------------------------------------------------------------
    if show_resource_table and fsp_data is not None and not fsp_data.empty:
        table_cols = [c for c in ["id", "type", "bus", "name", "mva"] if c in fsp_data.columns]
        table_df = fsp_data[table_cols].copy()

        # Shorten names in the table to keep it compact.
        if "name" in table_df.columns:
            table_df["name"] = table_df["name"].astype(str).apply(lambda x: _short_label(x, 20))

        # Round MVA values for readability.
        if "mva" in table_df.columns:
            table_df["mva"] = pd.to_numeric(table_df["mva"], errors="coerce").round(3)

        # Draw table outside the main map area.
        table = ax.table(
            cellText=table_df.astype(str).values.tolist(),
            colLabels=table_cols,
            cellLoc="left",
            colLoc="left",
            loc="right",
            bbox=[1.02, 0.04, 0.42, 0.88],
        )

        table.auto_set_font_size(False)
        table.set_fontsize(8)

        # Style header and alternating rows.
        for (r, c), cell in table.get_celld().items():
            cell.set_edgecolor("#d0d7de")
            if r == 0:
                cell.set_facecolor("#003A70")
                cell.set_text_props(color="white", weight="bold")
            else:
                cell.set_facecolor("#f8f9fa" if r % 2 == 0 else "white")

    # ------------------------------------------------------------------
    # 7. Formatting and saving
    # ------------------------------------------------------------------
    ax.annotate(
        "N",
        xy=(0.06, 0.92),
        xytext=(0.06, 0.82),
        xycoords="axes fraction",
        arrowprops=dict(facecolor="black", width=3, headwidth=10),
        ha="center",
        va="center",
        fontsize=12,
        fontweight="bold",
    )

    ax.text(
        0.01,
        0.02,
        "Radial single-line topology. Colors distinguish nominal voltage levels; purple links connect the primary substation and dotted magenta links are closed bus couplers.",
        transform=ax.transAxes,
        fontsize=9,
        color="#555555",
        ha="left",
        va="bottom",
    )

    ax.set_xlabel("Electrical depth from primary substation", fontsize=11)
    ax.set_ylabel("Radial branch order", fontsize=11)
    ax.grid(True, linestyle="--", alpha=0.22)
    ax.set_aspect("equal", adjustable="datalim")

    legend = ax.legend(
        loc="upper left",
        bbox_to_anchor=(0.01, 0.99),
        fontsize=9,
        frameon=True,
        framealpha=0.95,
    )
    legend.get_frame().set_edgecolor("#dddddd")

    plt.tight_layout()

    # HTML-only output policy: do not create static PNG/PDF/SVG files.
    # The save_* arguments are preserved for backward compatibility with old YAML
    # files and older calls, but are intentionally ignored here.
    save_png = False
    save_pdf = False
    save_svg = False

    if save_png:
        png_path = os.path.join(output_folder, filename + ".png")
        fig.savefig(png_path, dpi=dpi, bbox_inches="tight")
        print("Saved:", png_path)

    if save_pdf:
        pdf_path = os.path.join(output_folder, filename + ".pdf")
        fig.savefig(pdf_path, bbox_inches="tight")
        print("Saved:", pdf_path)

    if save_svg:
        svg_path = os.path.join(output_folder, filename + ".svg")
        fig.savefig(svg_path, bbox_inches="tight")
        print("Saved:", svg_path)

    return fig, ax


