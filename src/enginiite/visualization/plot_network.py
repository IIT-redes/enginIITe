def plot_base_pre_post_topology_bundle_html(
    net,
    ts_res,
    post_market_folder,
    hour,
    output_folder,
    market_tag,
    fsp_data=None,
    file_cfg_name="config",
    create_base_static_topology=False,
    create_base_topology_html=True,
    create_pre_market_html=True,
    create_post_market_html=True,
    create_comparison_dashboard=True,
    label_mode="compact",
    show_bus_labels=True,
    show_resource_table=False,
    save_png=False,
    save_pdf=False,
    save_svg=False,
    dpi=300,
):
    """
    Create the current topology visualization bundle for one scenario.

    Current output policy
    ---------------------
    1. HTML only. PNG/PDF/SVG exports are intentionally disabled.
    2. No separate pre-market/post-market files are generated for each hour.
    3. One single Plotly dashboard contains all studied hours and a slider.
    4. The base topology HTML can still be generated as a separate reference page.

    Saved under:
        <scenario_specific_visualization_folder>/network_topology/
    """
    if market_tag is None or _extract_market_tag_from_text(market_tag) is None:
        raise ValueError(
            "plot_base_pre_post_topology_bundle_html requires the full market_tag, "
            "for example 'net_CMVC_PQ_VL01_F05_SK01_T1'."
        )

    # All base, pre-market and
    # post-market views share one clear radial single-line bus layout.
    _apply_radial_single_line_layout(net)

    topology_folder = _get_network_plot_output_folder(
        output_folder=output_folder,
        market_tag=market_tag,
    )

    hour = int(hour)
    slider_hours = _available_topology_hours(ts_res=ts_res, post_market_folder=post_market_folder)
    if not slider_hours:
        slider_hours = [hour]

    created_paths = {
        "base_static_png": None,
        "base_static_pdf": None,
        "base_static_svg": None,
        "base_topology_html": None,
        "pre_market_html": None,
        "post_market_html": None,
        "pre_market_html_by_hour": {},
        "post_market_html_by_hour": {},
        "comparison_dashboard_html": None,
    }

    # Static image exports are intentionally ignored even if old YAML flags pass True.
    save_png = False
    save_pdf = False
    save_svg = False
    create_base_static_topology = False

    # Optional base HTML reference. This is one file only, not a repeated hourly file.
    if create_base_topology_html:
        base_html_filename = f"BaseTopologyInteractive_{market_tag}"
        plot_network_topology_with_fsp_html(
            net=net,
            fsp_data=fsp_data,
            output_folder=topology_folder,
            filename=base_html_filename,
            title="Base network topology and FSP locations",
            market_tag=market_tag,
        )
        created_paths["base_topology_html"] = os.path.join(topology_folder, base_html_filename + ".html")

    # Single all-hours comparison dashboard. No hourly HTMLs are saved.
    if create_comparison_dashboard:
        if post_market_folder is None or not os.path.exists(post_market_folder):
            print(
                "WARNING: Topology slider dashboard was skipped because the post-market folder was not found: "
                + str(post_market_folder)
            )
        else:
            created_paths["comparison_dashboard_html"] = _write_single_file_pre_post_slider_dashboard(
                net=net,
                ts_res=ts_res,
                post_market_folder=post_market_folder,
                hours=slider_hours,
                output_folder=topology_folder,
                filename=f"TopologyComparison_Pre_Post_AllHours_{market_tag}",
                market_tag=market_tag,
            )

    return created_paths
